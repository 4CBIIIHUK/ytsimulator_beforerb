/** Cumulative multiplier at given level: smooth curve from x1 to maxMult. */
export function upgradeMult(def: UpgradeDef, level: number): number {
  if (level <= 0) return 1;
  const l = Math.min(level, def.levels);
  const v = Math.exp(Math.log(def.maxMult) * Math.pow(l / def.levels, 1.2));
  return Math.round(v * 100) / 100;
}

export function upgradeCost(def: UpgradeDef, level: number): number {
  return Math.round(def.baseCost * Math.pow(def.costGrowth, level));
}

export function upgradeTierName(def: UpgradeDef, level: number): string {
  const idx = Math.min(def.tierNames.length - 1, Math.floor((level / def.levels) * def.tierNames.length));
  return def.tierNames[idx];
}

export function getUpgrade(id: string): UpgradeDef | undefined {
  return UPGRADES.find((u) => u.id === id);
}
